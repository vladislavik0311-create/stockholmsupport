create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 3 and 32),
  email text not null,
  role text not null default 'support' check (role in ('support','senior','admin')),
  branch_id bigint,
  created_at timestamptz not null default now()
);
create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name text not null unique,
  curator_user_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.profiles drop constraint if exists profiles_branch_id_fkey;
alter table public.profiles add constraint profiles_branch_id_fkey foreign key (branch_id) references public.branches(id) on delete set null;
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  branch_id bigint references public.branches(id) on delete cascade,
  title varchar(200) not null,
  description text,
  target integer not null default 1 check(target>0),
  progress integer not null default 0 check(progress>=0),
  due_date date,
  status text not null default 'active',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title varchar(200) not null,
  description text,
  starts_at timestamptz,
  branch_id bigint references public.branches(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title varchar(200) not null,
  body text not null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references public.profiles(id) on delete set null,
  action varchar(120) not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, username, email)
  values(new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email,'@',1)), new.email);
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.current_user_role()
returns text language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = (select auth.uid());
$$;

