drop policy if exists "profiles read authenticated" on public.profiles;
create policy "profiles read own or admin" on public.profiles for select to authenticated using (id=(select auth.uid()) or (select public.current_user_role())='admin');
drop policy if exists "profile update self limited" on public.profiles;
create policy "profile update self limited" on public.profiles for update to authenticated using (id=(select auth.uid())) with check (id=(select auth.uid()) and role=(select public.current_user_role()));
drop policy if exists "profiles admin update" on public.profiles;
create policy "profiles admin update" on public.profiles for update to authenticated using ((select public.current_user_role())='admin') with check ((select public.current_user_role())='admin');

