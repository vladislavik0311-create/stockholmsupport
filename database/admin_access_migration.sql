-- Stockholm Support: отдельный вход adm, владелец и управление администраторами.
-- Выполнить один раз в Supabase Dashboard -> SQL Editor.

alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check (role in ('support','senior','admin','owner'));
alter table public.profiles add column if not exists permissions jsonb not null default '{}'::jsonb;
alter table public.profiles add column if not exists admin_title text;
create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username));


create or replace function public.current_user_has_permission(permission_key text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select p.role='owner' or (p.role='admin' and coalesce((p.permissions->>permission_key)::boolean,false)) from public.profiles p where p.id=(select auth.uid())),false);
$$;
revoke all on function public.current_user_has_permission(text) from public;
grant execute on function public.current_user_has_permission(text) to authenticated;

drop policy if exists "profiles read own or admin" on public.profiles;
create policy "profiles read own or admin" on public.profiles for select to authenticated
using (id=(select auth.uid()) or (select public.current_user_role())='owner' or (select public.current_user_has_permission('manage_admins')));

-- RPC нужен для входа по логину (включая отдельный админ-логин adm).
create or replace function public.get_email_by_username(input_username text)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.email from public.profiles p where lower(p.username)=lower(trim(input_username)) limit 1;
$$;
revoke all on function public.get_email_by_username(text) from public;
grant execute on function public.get_email_by_username(text) to anon, authenticated;

create table if not exists public.admin_role_templates (
  id bigint generated by default as identity primary key,
  title text not null unique,
  permissions jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.admin_role_templates enable row level security;
drop policy if exists "admin role templates owner manage" on public.admin_role_templates;
create policy "admin role templates owner manage" on public.admin_role_templates
for all to authenticated
using ((select public.current_user_role())='owner')
with check ((select public.current_user_role())='owner');
grant select, insert, update, delete on public.admin_role_templates to authenticated;

-- Владелец и администраторы с manage_admins могут управлять профилями.
drop policy if exists "profiles admin update" on public.profiles;
create policy "profiles admin update" on public.profiles for update to authenticated
using ((select public.current_user_role())='owner' or ((select public.current_user_role())='admin' and (select public.current_user_has_permission('manage_admins')) and role <> 'owner'))
with check ((select public.current_user_role())='owner' or ((select public.current_user_role())='admin' and (select public.current_user_has_permission('manage_admins')) and role <> 'owner'));

-- Все ранее существовавшие административные политики расширяем на роль owner.
drop policy if exists "branches admin manage" on public.branches;
create policy "branches admin manage" on public.branches for all to authenticated
using ((select public.current_user_has_permission('manage_branches')))
with check ((select public.current_user_has_permission('manage_branches')));
drop policy if exists "tasks admin manage" on public.tasks;
create policy "tasks admin manage" on public.tasks for all to authenticated
using ((select public.current_user_has_permission('manage_tasks')))
with check ((select public.current_user_has_permission('manage_tasks')));
drop policy if exists "events admin manage" on public.events;
create policy "events admin manage" on public.events for all to authenticated
using ((select public.current_user_has_permission('manage_events')))
with check ((select public.current_user_has_permission('manage_events')));
drop policy if exists "announcements admin manage" on public.announcements;
create policy "announcements admin manage" on public.announcements for all to authenticated
using ((select public.current_user_has_permission('manage_bunny')))
with check ((select public.current_user_has_permission('manage_bunny')));
drop policy if exists "audit logs admin read" on public.audit_logs;
create policy "audit logs admin read" on public.audit_logs for select to authenticated
using ((select public.current_user_has_permission('view_audit')));
drop policy if exists "audit logs admin write" on public.audit_logs;
create policy "audit logs admin write" on public.audit_logs for insert to authenticated
with check ((select public.current_user_role()) in ('admin','owner'));

